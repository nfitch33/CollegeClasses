#pragma once
#include <string>
using namespace std;


/**
	 * @file
     * @brief returns the number of new lines found in a file
	 * @param input file
	 * @return int count of "\n" (new lines)
*/
int countLine(string text);

/**
     * @file
	 * @brief returns the number of characters in a given file
	 * @param input file
	 * @return int count of characters
	 */
int countChar(string text);
